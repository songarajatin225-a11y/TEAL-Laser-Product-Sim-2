#!/usr/bin/env node
/* Asset coverage and data completeness, from the records themselves.
 *
 *   node tools/cad/report.mjs          # rewrite assets/cad/COVERAGE.md
 *   node tools/cad/report.mjs --check  # exit 1 if COVERAGE.md is out of date
 *
 * Reads assets/cad/manifest.json, the component library (COMPINFO) in
 * index.html and data.json. Zero dependencies. The test suite runs --check so
 * the report can never silently disagree with the manifest.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, normalize } from 'node:path';

const ROOT = normalize(join(new URL('.', import.meta.url).pathname, '..', '..'));
const OUT = join(ROOT, 'assets/cad/COVERAGE.md');
const man = JSON.parse(readFileSync(join(ROOT, 'assets/cad/manifest.json'), 'utf8'));
const data = JSON.parse(readFileSync(join(ROOT, 'data.json'), 'utf8'));
const html = readFileSync(join(ROOT, 'index.html'), 'utf8');

/* COMPINFO keys, read from the source without executing it */
const ci = html.slice(html.indexOf('var COMPINFO = {'), html.indexOf('\n};', html.indexOf('var COMPINFO = {')));
const compIds = [...ci.matchAll(/^\s{2}([a-z0-9_]+)\s*:\{n:'([^']+)'/gm)].map(m => ({ id: m[1], n: m[2] }));
const C = man.components, ids = Object.keys(C);

const count = (f) => { const o = {}; for (const id of ids) { const k = f(C[id]); o[k] = (o[k] || 0) + 1; } return o; };
const pct = (n) => `${n} (${Math.round(n / ids.length * 100)} %)`;
const geo = count(r => r.glb ? (r.glb.status || 'cad-provisional') : r.geometry.status);
const cad = count(r => r.cad.status);
const idn = count(r => r.identity.status);
const ver = count(r => r.cad.verification || 'none');

const issues = [];
const inLib = new Set(compIds.map(c => c.id));
for (const c of compIds) if (!C[c.id]) issues.push(`Component library entry \`${c.id}\` has no manifest record.`);
for (const id of ids) if (!inLib.has(id)) issues.push(`Manifest record \`${id}\` has no component library entry.`);
for (const id of ids) {
  const r = C[id];
  if (r.glb && r.glb.file && !existsSync(join(ROOT, r.glb.file))) issues.push(`\`${id}\` names a GLB that does not exist: ${r.glb.file}`);
  if (r.cad.downloaded && !r.cad.file) issues.push(`\`${id}\` is marked downloaded but names no file.`);
  if (r.cad.verification === 'verified-exact' && !(r.identity.manufacturer && r.identity.partNumber))
    issues.push(`\`${id}\` claims an exact CAD match without a manufacturer and part number.`);
  for (const k of r.cad.candidates || []) if (!/^https:\/\//.test(k.url)) issues.push(`\`${id}\` has a candidate without an https URL.`);
}
const names = {};
for (const c of compIds) (names[c.n] = names[c.n] || []).push(c.id);
const dupes = Object.entries(names).filter(([, v]) => v.length > 1);

/* product-data completeness that bears on the machine model */
const P = data.PLAT, plats = Object.keys(P);
const noZ = plats.filter(k => P[k].deliv !== 'robot' && P[k].deliv !== 'handpiece' && !(P[k].specs || []).some(s => /^z.?axis/i.test(s[0])));
const lensNoWD = Object.keys(data.LENS);

const lines = [];
const L = (s = '') => lines.push(s);
L('# Asset coverage and data completeness');
L();
L(`Generated by \`tools/cad/report.mjs\` from \`manifest.json\` (checked ${man._checked}), the component library in`);
L('`index.html` and `data.json`. Do not edit by hand — edit the manifest and rerun the script.');
L();
L('## Asset coverage');
L();
L(`${ids.length} components can be drawn by the 3D model.`);
L();
L('| Geometry in the scene | Components |');
L('|---|---|');
for (const k of ['cad-verified-exact', 'cad-verified-equivalent', 'cad-provisional', 'parametric-provisional'])
  L(`| ${man.vocabulary['geometry.status'][k]} | ${pct(geo[k] || 0)} |`);
L();
L('**No component is drawn from verified CAD.** Every component the model shows is parametric geometry, illustrative in its proportions. The 3D model is a configuration-driven illustration, not a validated digital twin.');
L();
L('| CAD search result | Components |');
L('|---|---|');
for (const k of Object.keys(man.vocabulary['cad.status'])) L(`| ${man.vocabulary['cad.status'][k]} | ${pct(cad[k] || 0)} |`);
L();
L('| CAD verification | Components |');
L('|---|---|');
for (const k of ['verified-exact', 'verified-equivalent', 'provisional-reference', 'rejected', 'none'])
  L(`| ${k === 'none' ? 'No file obtained' : man.vocabulary['cad.verification'][k]} | ${pct(ver[k] || 0)} |`);
L();
L('### Per component');
L();
L('| ID | Component | Identity | CAD search | Geometry |');
L('|---|---|---|---|---|');
for (const id of ids.sort()) {
  const r = C[id];
  L(`| \`${id}\` | ${r.name} | ${r.identity.status} | ${r.cad.status} | ${r.glb ? (r.glb.status || 'cad-provisional') : r.geometry.status} |`);
}
L();
L('## Data completeness');
L();
L('| Check | Result |');
L('|---|---|');
L(`| Components with a manufacturer, model and part number | ${ids.filter(i => C[i].identity.partNumber).length} of ${ids.length} |`);
L(`| Bought-in components specified by class only | ${idn['class-only'] || 0} |`);
L(`| Components made to TEAL drawing (identity is the drawing number, not in the data) | ${idn['fabricated-to-drawing'] || 0} |`);
L(`| Components without a CAD file | ${ids.filter(i => !C[i].cad.file).length} of ${ids.length} |`);
L(`| Components not yet searched for CAD | ${cad['not-searched'] || 0} |`);
L(`| Library entries without a manifest record, or the reverse | ${issues.filter(s => /no manifest record|no component library/.test(s)).length} |`);
L(`| Component names used by more than one ID | ${dupes.length ? dupes.map(([n, v]) => `${n} (${v.join(', ')})`).join('; ') : 'none'} |`);
L(`| Platforms with a Z column but no Z stroke in the specification | ${noZ.length} of ${plats.length} — the Z joint uses the animation envelope for these |`);
L(`| Objectives with a stated working distance | 0 of ${lensNoWD.length} — only focal length and field are in the data, so the working distance is not shown |`);
L('| Component prices | Not itemised: the commercial model prices the platform, source and power adjustments, objective uplift, modules and software. |');
L('| Lead times | Platform level only (`PLAT.lead`, weeks). None per component. |');
L();
L('## Integrity issues');
L();
if (issues.length) issues.forEach(s => L(`- ${s}`)); else L('None found.');
L();
L('## Blockers and the inputs that resolve them');
L();
L(`- **Network:** ${man.blockers.network}`);
L(`- **Identity:** ${man.blockers.identity}`);
L('- **To resolve:** a TEAL engineering BOM with manufacturer, model and order number per bought-in part; TEAL\'s native or STEP export of the fabricated assemblies (frame, cabinet, Z column, table); and an environment that can reach the manufacturers\' CAD portals, or the files themselves.');
const text = lines.join('\n') + '\n';

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (cur !== text) { console.error('assets/cad/COVERAGE.md is out of date — run: node tools/cad/report.mjs'); process.exit(1); }
  if (issues.length) { console.error(issues.join('\n')); process.exit(1); }
  console.log(`COVERAGE.md current · ${ids.length} components · ${issues.length} integrity issues`);
} else {
  writeFileSync(OUT, text);
  console.log(`wrote ${OUT} · ${ids.length} components · ${issues.length} integrity issues`);
}
